"""Generates min-out.json: shared test vectors for FloorMath.minOut.

Expected values use Python's arbitrary-precision integers and the plain definition
    minOut = floor(floor(a * pIn * 10^dOut / (pOut * 10^dIn)) * (10000 - s) / 10000)
so they don't depend on either implementation. Checked by:
  - contracts/test/Vectors.t.sol (Solidity FloorMath)
  - packages/shared/test/math.test.ts (TypeScript mirror)
Run: python3 packages/shared/test/vectors/generate.py
"""
import json
import os
import random

U128 = 2**128 - 1
U256 = 2**256 - 1
rng = random.Random(20261010)  # fixed seed: the file is deterministic
DECIMALS = [6, 8, 18]


def expected(a, d_in, d_out, p_in, p_out, s):
    conv = a * p_in * 10**d_out // (p_out * 10**d_in)
    return conv * (10_000 - s) // 10_000


def fits(a, d_in, d_out, p_in, p_out):
    # FloorMath.convert must not overflow uint256 in mulDiv's result (and the scaled operands).
    if d_out >= d_in and a * 10 ** (d_out - d_in) > U256:
        return False
    return a * p_in * 10**d_out // (p_out * 10**d_in) <= U256


cases = []
# Hand-picked: the README / UI examples and rounding edges.
cases += [
    (1_000 * 10**18, 18, 6, 29 * 10**15, 10**18, 100),  # 1,000 MON at $0.029 -> USDC, 1%
    (10**6, 8, 6, 90_000 * 10**18, 10**18, 0),  # 0.01 BTC at $90k
    (100 * 10**6, 6, 18, 98 * 10**16, 33 * 10**15, 500),  # USDC depeg -> MON
    (1, 18, 6, 10**18, 10**18, 0),  # dust rounds to 0
    (1, 6, 18, 1, U128, 0),
    (U128, 18, 18, 1, 1, 500),
    (U128, 6, 6, U128, U128, 1),
]
while len(cases) < 300:
    d_in, d_out = rng.choice(DECIMALS), rng.choice(DECIMALS)
    a = rng.choice([rng.randint(1, 10**6), rng.randint(1, 10**24), rng.randint(1, U128)])
    p_in = rng.choice([rng.randint(1, 10**18), rng.randint(10**15, 10**24), rng.randint(1, U128)])
    p_out = rng.choice([rng.randint(10**17, 10**19), rng.randint(1, U128)])
    s = rng.choice([0, 1, 30, 100, 499, 500, rng.randint(0, 500)])
    if fits(a, d_in, d_out, p_in, p_out):
        cases.append((a, d_in, d_out, p_in, p_out, s))

cols = {k: [] for k in ["amountIn", "decIn", "decOut", "priceIn", "priceOut", "slippageBps", "minOut"]}
for a, d_in, d_out, p_in, p_out, s in cases:
    assert fits(a, d_in, d_out, p_in, p_out)
    for k, v in zip(cols, [a, d_in, d_out, p_in, p_out, s, expected(a, d_in, d_out, p_in, p_out, s)]):
        cols[k].append(str(v))  # strings: JSON numbers can't hold uint256

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "min-out.json")
with open(out, "w") as f:
    json.dump({"note": "generated by generate.py; columnar, values are decimal strings", **cols}, f, indent=1)
    f.write("\n")
print(f"wrote {len(cases)} vectors to {out}")
