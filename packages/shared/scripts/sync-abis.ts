/**
 * Copies contract ABIs from Foundry's build output (contracts/out) into typed TS constants,
 * so viem infers argument and return types. Run after `forge build`:
 *   pnpm --filter @floor/shared abi:sync     # write src/abi/generated.ts
 *   pnpm --filter @floor/shared abi:check    # CI: fail if the committed file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../contracts/out/', import.meta.url));
const target = fileURLToPath(new URL('../src/abi/generated.ts', import.meta.url));

const contracts: [exportName: string, artifact: string][] = [
  ['floorOrdersAbi', 'FloorOrders.sol/FloorOrders.json'],
  ['floorOracleAbi', 'IFloorOracle.sol/IFloorOracle.json'],
  ['pythAdapterAbi', 'PythAdapter.sol/PythAdapter.json'],
  ['mockOracleAbi', 'MockOracle.sol/MockOracle.json'],
  ['mockRouterAbi', 'MockRouter.sol/MockRouter.json'],
  ['mockErc20Abi', 'MockERC20.sol/MockERC20.json'],
];

let out =
  '// Generated by packages/shared/scripts/sync-abis.ts from contracts/out. Do not edit.\n' +
  '// Regenerate: forge build (in contracts/) then pnpm --filter @floor/shared abi:sync\n\n';
for (const [name, file] of contracts) {
  const { abi } = JSON.parse(readFileSync(root + file, 'utf8')) as { abi: unknown };
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== out) {
    console.error(
      'src/abi/generated.ts is stale: run forge build, then pnpm --filter @floor/shared abi:sync',
    );
    process.exit(1);
  }
  console.log('ABIs up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote ${contracts.length} ABIs to src/abi/generated.ts`);
}
